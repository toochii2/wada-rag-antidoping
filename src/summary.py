"""Write results/summary.md from results/metrics.json: headline numbers and hypothesis verdicts.

A hypothesis counts as supported for a model when the pre-specified test is in the
predicted direction with a Holm-adjusted p < 0.05 (H1, H4), or when the bootstrap
95% CI of the difference-in-differences excludes zero and retrieval did not raise false permits on
Group A (H2; a positive DiD produced by harm on fixed-status items is not support).
The restated H3 is post hoc and is reported as exploratory, at substance level.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
M = json.load(open(ROOT / "results/metrics.json"))
agp = ROOT / "results/rule_extraction_agreement.json"  # present only after the rule-table step
ag = json.load(open(agp)) if agp.exists() else None


def p(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def lab(m):
    return {"qwen3:30b-a3b": "Qwen3-30B-A3B", "qwen3:14b": "Qwen3-14B", "gemma3:12b": "Gemma3-12B",
            "llama3.1:8b": "Llama3.1-8B"}.get(m, m)


L = ["# Results summary (generated by src/summary.py)", "",
     f"Benchmark: {M['n_items']} items."
     + (f" Rule extraction pooled row-level agreement (Pass A vs Pass B): {100 * ag['pooled_row_level_agreement']:.1f}%."
        if ag else ""), "",
     "## Headline numbers (main run, temperature 0)", "",
     "| Model | Condition | Accuracy (6-way) | Safety-verdict accuracy | False-permit rate (Wilson 95% CI) | Any-permit rate | Harm per item | Deferral, newly named (Group C) | Appropriate deferral (Group D) |",
     "|---|---|---|---|---|---|---|---|---|"]
for m in M["models"]:
    for c in ("C0", "C1", "C2"):
        r = M["per"].get(f"{m}|{c}")
        if not r:
            continue
        ci = r.get("false_permit_ci", [None, None])
        L.append(f"| {lab(m)} | {c} | {p(r['acc6'])} | {p(r['acc_collapsed'])} | {p(r['false_permit'])} ({p(ci[0])} to {p(ci[1])}) | "
                 f"{p(r['lenient_permit'])} | {r['harm']:.2f} | {p(r.get('nn_defer'))} | {p(r.get('appropriate_deferral'))} |")
L += ["", "## Hypotheses", ""]


def verdict(key, direction):
    out = []
    for m in M["models"]:
        t = M["tests"].get(f"{m}|{key}")
        if not t:
            continue
        ok = (t["rate_first"] > t["rate_second"]) if direction == "down" else (t["rate_first"] < t["rate_second"])
        sig = t["p_holm"] < 0.05
        out.append((m, ok and sig, t))
    return out


def line(name, res, desc):
    n_sup = sum(1 for _, s, _ in res if s)
    L.append(f"- **{name}** {desc}: supported in {n_sup} of {len(res)} models.")
    for m, s, t in res:
        L.append(f"  - {lab(m)}: {p(t['rate_first'])} vs {p(t['rate_second'])}, discordant {t['only_first']}/{t['only_second']}, "
                 f"Holm p = {t['p_holm']:.3f}{' (supported)' if s else ''}")


line("H1", verdict("C0vC1", "down"), "RAG-2027 lowers the false-permit rate versus closed-book")
h2 = M.get("h2", {})
n2 = sum(1 for v in h2.values() if "ci" in v and v["ci"][0] > 0 and v["adv_A"] >= 0)
L.append(f"- **H2** the false-permit advantage of RAG is larger for context-dependent (B) than fixed-status (A) items: "
         f"supported in {n2} of {sum(1 for v in h2.values() if 'ci' in v)} models.")
for m, v in h2.items():
    if "ci" in v:
        L.append(f"  - {lab(m)}: advantage A {p(v['adv_A'])}, B {p(v['adv_B'])}, difference {p(v['did'])} "
                 f"(95% CI {p(v['ci'][0])} to {p(v['ci'][1])})"
                 + (" (positive only because RAG raised false permits on Group A; not support)" if v["ci"][0] > 0 and v["adv_A"] < 0 else ""))
L.append("- **H3 (restated post hoc, exploratory)** the stale 2026 index raises deferral on the nine substances first named in 2027. "
         "Substance-level sign tests (higher with 2026 / substances that differed, Holm p):")
for m, s in M.get("nn_sign", {}).items():
    L.append(f"  - {lab(m)}: {s['higher_with_2026']}/{s['higher_with_2026'] + s['lower_with_2026']}, Holm p = {s['p_holm']:.3f}")
line("Safety-verdict accuracy, RAG-2027 vs RAG-2026", verdict("accs_C1vC2", "down"), "the stale index lowers safety-verdict accuracy (direction: C1 higher)")
line("Safety-verdict accuracy, closed-book vs RAG-2027", verdict("accs_C0vC1", "up"), "RAG-2027 raises safety-verdict accuracy")
line("H3 safety check", verdict("nnfp_C1vC2", "up"), "the stale 2026 index raises false permits on substances first named in 2027")
L.append("- Note: the 2027 revision contained no change of status that the List text settles (the newly named substances were already prohibited by class in 2026; S8 narrowed its wording for natural non-THC cannabinoids, which were excluded as unsettled), so H3 as originally worded (reproducing 2026 answers) could not be tested.")
line("H4", verdict("defer_C0vC1", "up"), "RAG-2027 raises appropriate deferral on Group D items versus closed-book")
S = M.get("statuschange")
if S:
    n_sup = 0
    rows = []
    for m in M["models"]:
        r = S["tests"].get(f"{m}|C1vCH")
        if r:
            ok = r["rate_second"] > r["rate_first"] and r["p_holm"] < 0.05
            n_sup += ok
            rows.append(f"  - {lab(m)}: current {p(r['rate_first'])} vs pre-change List {p(r['rate_second'])}, discordant "
                        f"{r['only_first']}/{r['only_second']}, Holm p = {r['p_holm']:.3f}{' (supported)' if ok else ''}")
    L.append(f"- **H3 as pre-specified, status-change arm** (glucocorticoid injections 2021 to 2022; tramadol 2023 to 2024) "
             f"a pre-change index raises false permits on changed items versus the current index: supported in {n_sup} of {len(rows)} models.")
    L += rows
bl = M["baselines"]
L += ["", f"Trivial baselines (safety-verdict accuracy): always prohibited {100 * bl['prohibited_at_all_times']['acc_collapsed']:.1f}%, "
      f"always refer {100 * bl['cannot_determine_refer']['acc_collapsed']:.1f}%."]
L += ["", f"Trivial baselines (mean harm): always refer {bl['cannot_determine_refer']['harm']:.2f}, always prohibited "
      f"{bl['prohibited_at_all_times']['harm']:.2f}, always permitted {bl['permitted']['harm']:.2f}; best model and condition "
      f"{min(v['harm'] for v in M['per'].values()):.2f}."]
L += ["", f"Weight sensitivity: model or condition ranking changes under at least one weight set: "
      f"{'yes' if M.get('sensitivity_rank_change') else 'no'}.",
      f"Mixed-effects model converged: {M.get('mixed', {}).get('converged')}."]
(ROOT / "results/summary.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
